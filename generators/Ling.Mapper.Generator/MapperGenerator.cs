using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Ling.Mapper.Generator;

[Generator]
public sealed class MapperGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidPair = new("LMG001", "Unsupported generated mapping pair", "Cannot generate {0}: {1}", "Ling.Mapper", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidMember = new("LMG002", "Unsupported generated member mapping", "Cannot generate {0}.{1}: {2}. Declare the nested GeneratedMap pair or use the runtime mapper.", "Ling.Mapper", DiagnosticSeverity.Error, true);
    public void Initialize(IncrementalGeneratorInitializationContext context)
        => context.RegisterSourceOutput(context.CompilationProvider, Generate);

    private static void Generate(SourceProductionContext context, Compilation compilation)
    {
        var pairs = compilation.Assembly.GetAttributes()
            .Where(a => a.AttributeClass?.ToDisplayString() == "Ling.Mapper.GeneratedMapAttribute" && a.ConstructorArguments.Length == 2)
            .Select(a => new Pair((ITypeSymbol)a.ConstructorArguments[0].Value!, (ITypeSymbol)a.ConstructorArguments[1].Value!, a.ApplicationSyntaxReference?.GetSyntax().GetLocation()))
            .GroupBy(p => Name(p.Source) + ":" + Name(p.Destination)).Select(g => g.First()).ToList();
        if (pairs.Count == 0) return;
        ExpandAutomaticClonePairs(pairs);
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Ling.Mapper.Generated {\ninternal static class GeneratedMappings {\n");
        // Scalar enum conversion shares runtime EnumMember rules. Preserve metadata for
        // every statically known enum instead of depending on incidental JIT retention.
        foreach (var enumType in KnownEnums(pairs))
            code.Append("[global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicFields, typeof(")
                .Append(Name(enumType)).Append("))]\n");
        code.Append("[global::System.Runtime.CompilerServices.ModuleInitializer] internal static void Register() {\n");
        for (int i = 0; i < pairs.Count; i++)
        {
            var sourceItem = Item(pairs[i].Source); var destinationItem = Item(pairs[i].Destination);
            if (sourceItem != null && destinationItem != null && !HasPair(pairs, sourceItem, destinationItem) && DynamicSource(sourceItem))
                code.Append("global::Ling.Mapper.GeneratedMapperRegistry.RegisterCollectionShapes<").Append(Name(sourceItem)).Append(", ").Append(Name(destinationItem)).Append(">();\n");
            code.Append("global::Ling.Mapper.GeneratedMapperRegistry.Register<").Append(Name(pairs[i].Source)).Append(", ").Append(Name(pairs[i].Destination)).Append(">(Map").Append(i).Append(");\n");
        }
        code.Append("}\n");
        for (int index = 0; index < pairs.Count; index++)
        {
            var pair = pairs[index];
            code.Append("private static ").Append(Name(pair.Destination)).Append(" Map").Append(index).Append('(').Append(Name(pair.Source))
                .Append(" source, global::Ling.Mapper.Models.AdaptOptions options, string[]? ignores, global::Ling.Mapper.GeneratedMappingContext context) {\n");
            if (pair.DiscoveryError != null)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), pair.DiscoveryError));
                code.Append("throw new global::System.NotSupportedException(); }\n");
                continue;
            }
            if (IsImmutableAtom(pair.Source) && (Assignable(pair.Source, pair.Destination) || pair.Destination.SpecialType == SpecialType.System_Object))
            {
                code.Append("return source;\n}\n");
                continue;
            }
            if (IsScalar(pair.Source) && IsScalar(pair.Destination))
            {
                code.Append("return ").Append(ConvertExpression(pair.Source, pair.Destination, "source", pairs)).Append(";\n}\n");
                continue;
            }
            var sourceItem = Item(pair.Source);
            var destinationItem = Item(pair.Destination);
            if (sourceItem != null && destinationItem != null && (HasPair(pairs, sourceItem, destinationItem) || DynamicSource(sourceItem)))
            {
                var method = pair.Destination is IArrayTypeSymbol ? "CopyArray" : "CopyList";
                var sourceShape = pair.Destination is IArrayTypeSymbol ? "global::System.Collections.Generic.ICollection<" : "global::System.Collections.Generic.IEnumerable<";
                code.Append("return (").Append(Name(pair.Destination)).Append(")(object)context.").Append(method).Append('<')
                    .Append(Name(sourceItem)).Append(", ").Append(Name(destinationItem)).Append(">((")
                    .Append(sourceShape).Append(Name(sourceItem)).Append(">)source!, options, ignores);\n}\n");
                continue;
            }
            if ((IsNullable(pair.Source) || IsNullable(pair.Destination)) &&
                SymbolEqualityComparer.Default.Equals(Unwrap(pair.Source), Unwrap(pair.Destination)) &&
                HasPair(pairs, Unwrap(pair.Source), Unwrap(pair.Destination)))
            {
                code.Append("return ").Append(NullableCloneExpression(pair.Source, pair.Destination, "source")).Append(";\n}\n");
                continue;
            }
            var operators = Operators(pair.Source, pair.Destination);
            if (operators.Length != 0)
            {
                if (operators.Length != 1)
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "multiple exact user-defined conversions exist; use an explicit generated mapping delegate"));
                    code.Append("throw new global::System.NotSupportedException(); }\n");
                    continue;
                }
                if (IsRefLike(pair.Source) || IsRefLike(pair.Destination))
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "ref-like types cannot participate in the mapper's boxed-value contract"));
                    code.Append("throw new global::System.NotSupportedException(); }\n");
                    continue;
                }
                // Generated dispatch caches reference-source results; runtime opaque
                // operators execute per occurrence. Do not silently change that contract.
                if (Unwrap(pair.Source).IsReferenceType)
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "reference-source root operators are unsupported because generated reference caching would change operator invocation counts; use the runtime mapper"));
                    code.Append("throw new global::System.NotSupportedException(); }\n");
                    continue;
                }
                if (IsNullable(pair.Source))
                {
                    var boxedOperators = Operators(Unwrap(pair.Source), pair.Destination);
                    if (boxedOperators.Length != 1 || !SymbolEqualityComparer.Default.Equals(operators[0], boxedOperators[0]))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "nullable-source operator selection differs after boxing; generated root aliases cannot preserve both declared and actual-source semantics"));
                        code.Append("throw new global::System.NotSupportedException(); }\n");
                        continue;
                    }
                }
                code.Append("if (ignores is { Length: > 0 }) throw new global::System.NotSupportedException(\"Member ignore projections cannot be applied inside a user-defined conversion.\");\n");
                code.Append("return ").Append(OperatorExpression(pair.Source, pair.Destination, "source", operators[0])).Append(";\n}\n");
                continue;
            }
            if (IsResourceDestination(pair.Destination))
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "resource/delegate destinations, including user-defined resource subclasses, require an explicit final mapping delegate; automatic copying is unsupported"));
                code.Append("throw new global::System.NotSupportedException(); }\n");
                continue;
            }
            if (pair.Source is not INamedTypeSymbol sourceType || pair.Destination is not INamedTypeSymbol destinationType ||
                sourceType.IsUnboundGenericType || destinationType.IsUnboundGenericType || destinationType.IsAbstract ||
                sourceType.SpecialType != SpecialType.None || destinationType.SpecialType != SpecialType.None ||
                IsFrameworkType(sourceType) ||
                IsFrameworkType(destinationType) ||
                (destinationType.TypeKind != TypeKind.Class && destinationType.TypeKind != TypeKind.Struct) ||
                !destinationType.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public) ||
                Properties(destinationType).Any(p => p.IsRequired || p.SetMethod?.IsInitOnly == true))
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), "destination must be a concrete DTO with a public parameterless constructor and no required/init members"));
                code.Append("throw new global::System.NotSupportedException(); }\n"); continue;
            }
            if (SymbolEqualityComparer.Default.Equals(pair.Source, pair.Destination) && !CanCopyDtoState(sourceType, out var stateReason))
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidPair, pair.Location, Name(pair.Source) + " -> " + Name(pair.Destination), stateReason));
                code.Append("throw new global::System.NotSupportedException(); }\n");
                continue;
            }
            code.Append("var destination = new ").Append(Name(pair.Destination)).Append("();\n");
            if (pair.Source.IsReferenceType && pair.Destination.IsReferenceType)
                code.Append("context.Remember(source!, typeof(").Append(Name(pair.Destination)).Append("), destination!);\n");
            var sources = Properties(sourceType).Where(p => p.GetMethod?.DeclaredAccessibility == Accessibility.Public && !p.IsStatic && !p.IsIndexer).ToArray();
            foreach (var destination in Properties(destinationType).Where(p => p.SetMethod?.DeclaredAccessibility == Accessibility.Public && !p.IsStatic && !p.IsIndexer))
            {
                var candidates = sources.Where(p => Normalize(p.Name) == Normalize(destination.Name)).OrderByDescending(p => p.Name == destination.Name).ThenBy(p => p.Name, StringComparer.Ordinal).ToArray();
                if (candidates.Length == 0) continue;
                code.Append("if (ignores == null || global::System.Array.IndexOf(ignores, ").Append(Literal(destination.Name)).Append(") < 0) {\n");
                if (candidates.Length > 1)
                {
                    code.Append("if (");
                    code.Append(string.Join(" + ", candidates.Select(candidate => "(global::Ling.Mapper.GeneratedMappingContext.Matches(" + Literal(candidate.Name) + ", " + Literal(destination.Name) + ", options) ? 1 : 0)")));
                    code.Append(" > 1) context.Member(typeof(").Append(Name(pair.Source)).Append("), typeof(").Append(Name(destination.Type)).Append("), ").Append(Literal(destination.Name)).Append(", () => { throw new global::System.InvalidOperationException(\"Multiple source members match the destination member.\"); });\n");
                }
                bool first = true;
                foreach (var source in candidates)
                {
                    var expression = ConvertExpression(source.Type, destination.Type, "value", pairs);
                    if (expression == null)
                    {
                        var reason = Name(source.Type) + " -> " + Name(destination.Type);
                        if (Operators(source.Type, destination.Type).Length > 1) reason += " (multiple exact user-defined conversions)";
                        else if (IsRefLike(source.Type) || IsRefLike(destination.Type)) reason += " (ref-like types cannot participate in the mapper's boxed-value contract)";
                        else if (RuntimeDispatchesSource(source.Type) && Operators(source.Type, destination.Type).Length != 0)
                            reason += " (abstract/interface source operator requires actual-runtime-type dispatch)";
                        context.ReportDiagnostic(Diagnostic.Create(InvalidMember, pair.Location, Name(pair.Destination), destination.Name, reason));
                        continue;
                    }
                    code.Append(first ? "if (" : "else if (").Append("global::Ling.Mapper.GeneratedMappingContext.Matches(").Append(Literal(source.Name)).Append(", ").Append(Literal(destination.Name)).Append(", options)) {\n");
                    first = false;
                    code.Append("using (context.EnterMember(").Append(Literal(destination.Name)).Append(", ").Append(Sensitive(source.Name) || Sensitive(destination.Name) ? "true" : "false").Append(")) {\ntry {\nvar value = source.@").Append(source.Name).Append(";\n");
                    if (CanBeNull(source.Type)) code.Append("if (value is not null || (options & global::Ling.Mapper.Models.AdaptOptions.IgnoreNullValues) == 0) ");
                    code.Append("destination.@").Append(destination.Name).Append(" = ").Append(expression).Append(";\n} catch (global::System.Exception error) when (!context.OwnsException(error)) { throw context.MemberException(typeof(").Append(Name(source.Type)).Append("), typeof(").Append(Name(destination.Type)).Append("), error); }\n}\n}\n");
                }
                code.Append("}\n");
            }
            code.Append("return destination;\n}\n");
        }
        code.Append("}\n}\n");
        context.AddSource("LingMapper.Generated.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
    }

    private static string? ConvertExpression(ITypeSymbol source, ITypeSymbol destination, string value, List<Pair> pairs)
    {
        // Identical immutable values need no conversion or boxing. Nullable identity still preserves null.
        if (SymbolEqualityComparer.Default.Equals(source, destination) && IsImmutableAtom(source)) return value;
        if (IsScalar(source) && IsScalar(destination))
            return "context.Scalar<" + Name(source) + ", " + Name(destination) + ">(" + value + "!)";
        // Assignability is not ownership: only immutable atomic values may be shared.
        if (IsImmutableAtom(source) && (Assignable(source, destination) || destination.SpecialType == SpecialType.System_Object)) return value;
        var operators = Operators(source, destination);
        if (operators.Length != 0)
            return operators.Length == 1 && !RuntimeDispatchesSource(source) && !IsRefLike(source) && !IsRefLike(destination) ? OperatorExpression(source, destination, value, operators[0]) : null;
        if ((IsNullable(source) || IsNullable(destination)) && SymbolEqualityComparer.Default.Equals(Unwrap(source), Unwrap(destination)) &&
            HasPair(pairs, Unwrap(source), Unwrap(destination)))
            return NullableCloneExpression(source, destination, value);
        if (HasPair(pairs, source, destination)) return ContextMap(source, destination, value);
        var sourceItem = Item(source); var destinationItem = Item(destination);
        if (sourceItem != null && destinationItem != null && (HasPair(pairs, sourceItem, destinationItem) || DynamicSource(sourceItem)))
            return ContextMap(source, destination, value);
        // Dynamic slots are safe only through registered runtime pairs; Dispatch throws
        // for unknown mutable values, instead of silently returning the original object.
        if (source.SpecialType == SpecialType.System_Object || RuntimeDispatchesSource(source))
            return IsRefLike(destination) ? null : ContextMap(source, destination, value);
        if ((Assignable(source, destination) || destination.SpecialType == SpecialType.System_Object) &&
            (HasPair(pairs, source, source) || sourceItem != null && HasPair(pairs, sourceItem, sourceItem)))
            return ContextMap(source, destination, value);
        return null;
    }
    private static bool DynamicSource(ITypeSymbol source) => source.SpecialType == SpecialType.System_Object || RuntimeDispatchesSource(source);
    private static string ContextMap(ITypeSymbol source, ITypeSymbol destination, string value)
        => "context.Map<" + Name(source) + ", " + Name(destination) + ">(" + value + "!, options)";
    private static string NullableCloneExpression(ITypeSymbol source, ITypeSymbol destination, string value)
    {
        var expression = "(" + Name(destination) + ")(" + ContextMap(Unwrap(source), Unwrap(destination), IsNullable(source) ? value + ".Value" : value) + ")";
        return IsNullable(source) ? "(" + value + " is null ? context.Null<" + Name(destination) + ">(typeof(" + Name(source) + ")) : " + expression + ")" : expression;
    }
    private static bool HasPair(IEnumerable<Pair> pairs, ITypeSymbol source, ITypeSymbol destination)
        => pairs.Any(pair => SymbolEqualityComparer.Default.Equals(pair.Source, source) && SymbolEqualityComparer.Default.Equals(pair.Destination, destination));

    private static void ExpandAutomaticClonePairs(List<Pair> pairs)
    {
        Pair? parent = null;
        static IEnumerable<INamedTypeSymbol> Definitions(ITypeSymbol source, ITypeSymbol destination)
            => new[] { Unwrap(source), Unwrap(destination) }.OfType<INamedTypeSymbol>()
                .Where(type => type.IsGenericType && !IsFrameworkType(type)).Select(type => type.OriginalDefinition);
        void Add(ITypeSymbol source, ITypeSymbol destination, Location? location)
        {
            if (HasPair(pairs, source, destination)) return;
            var ancestors = parent?.DiscoveryAncestors?.ToList() ?? new List<INamedTypeSymbol>();
            if (parent != null) ancestors.AddRange(Definitions(parent.Source, parent.Destination));
            var next = new Pair(source, destination, location) { DiscoveryAncestors = ancestors };
            if (Definitions(source, destination).Any(definition => ancestors.Any(ancestor => SymbolEqualityComparer.Default.Equals(ancestor, definition))))
                next.DiscoveryError = "expanding generic recursion cannot be automatically discovered as a finite graph; provide explicit bounded DTO shapes";
            pairs.Add(next);
        }
        void Shape(ITypeSymbol source, ITypeSymbol destination, Location? location, bool collectionItem = false)
        {
            if (IsScalar(source) && IsScalar(destination)) { if (collectionItem) Add(source, destination, location); return; }
            var sourceItem = Item(source); var destinationItem = Item(destination);
            if (sourceItem != null && destinationItem != null)
            {
                Shape(sourceItem, destinationItem, location, true);
                if (HasPair(pairs, sourceItem, destinationItem) || DynamicSource(sourceItem)) Add(source, destination, location);
                return;
            }
            if (sourceItem != null && destination.SpecialType == SpecialType.System_Object)
            { Shape(source, source, location, true); return; }
            if (SymbolEqualityComparer.Default.Equals(Unwrap(source), Unwrap(destination)))
            {
                if (source.SpecialType == SpecialType.System_Object || RuntimeDispatchesSource(source)) return;
                if (IsNullable(source) || IsNullable(destination)) Add(Unwrap(source), Unwrap(destination), location);
                Add(source, destination, location);
                return;
            }
            if (IsScalar(source)) return;
            if ((Assignable(source, destination) || destination.SpecialType == SpecialType.System_Object) &&
                source.SpecialType != SpecialType.System_Object && !RuntimeDispatchesSource(source))
                Shape(source, source, location, true);
        }
        // The list grows only by finite declared shapes; self/circular DTOs are deduplicated.
        for (int index = 0; index < pairs.Count; index++)
        {
            var pair = pairs[index];
            parent = pair;
            if (pair.DiscoveryError != null) continue;
            var sourceItem = Item(pair.Source); var destinationItem = Item(pair.Destination);
            if (sourceItem != null && destinationItem != null) { Shape(sourceItem, destinationItem, pair.Location, true); continue; }
            if (IsNullable(pair.Source) || IsNullable(pair.Destination))
            { Shape(Unwrap(pair.Source), Unwrap(pair.Destination), pair.Location, true); continue; }
            if (IsScalar(pair.Source) || IsScalar(pair.Destination) ||
                pair.Source is not INamedTypeSymbol source || pair.Destination is not INamedTypeSymbol destination ||
                IsFrameworkType(source) || IsFrameworkType(destination)) continue;
            var sourceProperties = Properties(source).Where(property => property.GetMethod?.DeclaredAccessibility == Accessibility.Public && !property.IsStatic && !property.IsIndexer).ToArray();
            foreach (var target in Properties(destination).Where(property => property.SetMethod?.DeclaredAccessibility == Accessibility.Public && !property.IsStatic && !property.IsIndexer))
                foreach (var member in sourceProperties.Where(property => Normalize(property.Name) == Normalize(target.Name)))
                    Shape(member.Type, target.Type, pair.Location);
        }
    }
    private static bool CanCopyDtoState(INamedTypeSymbol type, out string reason)
    {
        for (INamedTypeSymbol? current = type; current != null && current.SpecialType != SpecialType.System_Object && current.SpecialType != SpecialType.System_ValueType; current = current.BaseType)
            foreach (var field in current.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic))
                if (!field.IsImplicitlyDeclared || field.AssociatedSymbol is not IPropertySymbol property ||
                    property.GetMethod?.DeclaredAccessibility != Accessibility.Public || property.SetMethod?.DeclaredAccessibility != Accessibility.Public)
                { reason = "same-type copying cannot preserve field-only, private or read-only state without data loss; use a mutable property DTO or an explicit generated mapping delegate"; return false; }
        foreach (var property in Properties(type).Where(property => !property.IsStatic && !property.IsIndexer && property.GetMethod?.DeclaredAccessibility == Accessibility.Public))
            if (property.SetMethod?.DeclaredAccessibility != Accessibility.Public)
            { reason = "same-type copying requires publicly writable properties; use an explicit generated mapping delegate for immutable constructor state"; return false; }
        reason = "";
        return true;
    }
    private static IMethodSymbol[] Operators(ITypeSymbol source, ITypeSymbol destination)
    {
        // Preserve the full declared pair before considering nullable promotion/lifting.
        var sourceCore = Unwrap(source); var destinationCore = Unwrap(destination);
        if (SimpleForOperators(sourceCore) && SimpleForOperators(destinationCore)) return Array.Empty<IMethodSymbol>();
        var methods = new[] { sourceCore, destinationCore }.Distinct(SymbolEqualityComparer.Default)
            .OfType<INamedTypeSymbol>().SelectMany(type => type.GetMembers().OfType<IMethodSymbol>())
            .Where(method => method.MethodKind == MethodKind.Conversion && method.IsStatic &&
                method.DeclaredAccessibility == Accessibility.Public && !method.IsGenericMethod &&
                (method.Name == "op_Implicit" || method.Name == "op_Explicit") && method.Parameters.Length == 1).ToArray();
        var exact = methods.Where(method => SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, source) &&
            SymbolEqualityComparer.Default.Equals(method.ReturnType, destination)).ToArray();
        if (exact.Length != 0) return exact;
        return methods.Where(method => SymbolEqualityComparer.Default.Equals(Unwrap(method.Parameters[0].Type), sourceCore) &&
            (SymbolEqualityComparer.Default.Equals(method.ReturnType, destination) ||
             (IsNullable(destination) && SymbolEqualityComparer.Default.Equals(method.ReturnType, destinationCore)))).ToArray();
    }
    private static bool IsRefLike(ITypeSymbol type) => Unwrap(type) is INamedTypeSymbol named && named.IsRefLikeType;
    private static bool RuntimeDispatchesSource(ITypeSymbol type)
        => type is INamedTypeSymbol named && (named.IsAbstract || named.TypeKind == TypeKind.Interface);
    private static bool SimpleForOperators(ITypeSymbol type)
        => IsScalar(type) || type.SpecialType == SpecialType.System_IntPtr || type.SpecialType == SpecialType.System_UIntPtr;
    private static string OperatorExpression(ITypeSymbol source, ITypeSymbol destination, string value, IMethodSymbol method)
    {
        // Explicitly type both ends to select the same declaration as the runtime.
        // Never let a consumer's checked build select op_CheckedExplicit instead.
        var parameter = method.Parameters[0].Type;
        string input = IsNullable(source) && !IsNullable(parameter) ? value + ".Value" : value;
        input = "(" + Name(parameter) + ")(" + input + ")";
        string expression = "unchecked((" + Name(method.ReturnType) + ")(" + input + "))";
        if (!SymbolEqualityComparer.Default.Equals(method.ReturnType, destination)) expression = "(" + Name(destination) + ")(" + expression + ")";
        return CanBeNull(source) ? "(" + value + " is null ? context.Null<" + Name(destination) + ">(typeof(" + Name(source) + ")) : " + expression + ")" : expression;
    }
    private static IEnumerable<ITypeSymbol> KnownEnums(IEnumerable<Pair> pairs)
    {
        var result = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        void Add(ITypeSymbol type)
        {
            type = Unwrap(type);
            if (type.TypeKind == TypeKind.Enum) result.Add(type);
            else if (type is IArrayTypeSymbol array) Add(array.ElementType);
            else if (type is INamedTypeSymbol named)
                foreach (var argument in named.TypeArguments) Add(argument);
        }
        foreach (var pair in pairs)
            foreach (var type in new[] { pair.Source, pair.Destination })
            {
                Add(type);
                if (Unwrap(type) is INamedTypeSymbol named)
                    foreach (var property in Properties(named)) Add(property.Type);
            }
        return result.OrderBy(Name, StringComparer.Ordinal);
    }
    private static bool IsResourceDestination(ITypeSymbol type)
    {
        if (Unwrap(type) is not INamedTypeSymbol named) return false;
        if (named.AllInterfaces.Any(contract => contract.ToDisplayString() is "System.IDisposable" or "System.IAsyncDisposable") ||
            named.ToDisplayString() is "System.IDisposable" or "System.IAsyncDisposable") return true;
        for (INamedTypeSymbol? current = named; current != null; current = current.BaseType)
            if (current.ToDisplayString() is "System.Threading.Tasks.Task" or "System.Delegate" or "System.MulticastDelegate") return true;
        return false;
    }
    private static bool IsFrameworkType(INamedTypeSymbol type)
    {
        var ns = type.ContainingNamespace.ToDisplayString();
        return ns == "System" || ns.StartsWith("System.", StringComparison.Ordinal);
    }
    private static bool Assignable(ITypeSymbol source, ITypeSymbol destination)
    {
        if (SymbolEqualityComparer.Default.Equals(source, destination)) return true;
        if (source is IArrayTypeSymbol || destination is IArrayTypeSymbol) return false;
        if (source is INamedTypeSymbol named)
        {
            for (var current = named.BaseType; current != null; current = current.BaseType)
                if (SymbolEqualityComparer.Default.Equals(current, destination)) return true;
            if (named.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, destination))) return true;
        }
        return false;
    }
    private static IEnumerable<IPropertySymbol> Properties(INamedTypeSymbol type)
    {
        var names = new HashSet<string>();
        for (INamedTypeSymbol? current = type; current != null; current = current.BaseType)
            foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
                if (names.Add(property.Name)) yield return property;
    }
    private static ITypeSymbol? Item(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol array && array.Rank == 1) return array.ElementType;
        if (type is INamedTypeSymbol named && named.TypeArguments.Length == 1 && new[] { "System.Collections.Generic.List<T>", "System.Collections.Generic.IEnumerable<T>", "System.Collections.Generic.IList<T>", "System.Collections.Generic.IReadOnlyList<T>" }.Contains(named.OriginalDefinition.ToDisplayString())) return named.TypeArguments[0];
        return null;
    }
    private static ITypeSymbol Unwrap(ITypeSymbol type) => IsNullable(type) ? ((INamedTypeSymbol)type).TypeArguments[0] : type;
    private static bool IsNullable(ITypeSymbol type) => type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
    private static bool CanBeNull(ITypeSymbol type) => type.IsReferenceType || IsNullable(type);
    private static bool IsImmutableAtom(ITypeSymbol type)
        => IsScalar(type) || new[] { "System.Half", "System.Int128", "System.UInt128" }.Contains(Unwrap(type).ToDisplayString());
    private static bool IsScalar(ITypeSymbol type)
    {
        type = Unwrap(type);
        return type.TypeKind == TypeKind.Enum || (type.SpecialType >= SpecialType.System_Boolean && type.SpecialType <= SpecialType.System_Double) || type.SpecialType == SpecialType.System_String ||
            new[] { "System.DateTime", "System.DateTimeOffset", "System.DateOnly", "System.TimeOnly", "System.TimeSpan", "System.Guid" }.Contains(type.ToDisplayString());
    }
    private static string Name(ITypeSymbol type) => type.WithNullableAnnotation(NullableAnnotation.None).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static string Normalize(string name) => name.Replace("_", "").ToUpperInvariant();
    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    private static bool Sensitive(string name) => new[] { "password", "passwd", "pwd", "token", "secret", "credential", "encrypt", "cipher", "privatekey", "apikey" }.Any(word => name.IndexOf(word, StringComparison.OrdinalIgnoreCase) >= 0);
    private sealed class Pair
    {
        public readonly ITypeSymbol Source, Destination;
        public readonly Location? Location;
        public List<INamedTypeSymbol>? DiscoveryAncestors;
        public string? DiscoveryError;
        public Pair(ITypeSymbol source, ITypeSymbol destination, Location? location) { Source = source; Destination = destination; Location = location; }
    }
